def signature(name):
    """商品名から宣伝文句・数量・ジャンル共通語を除いた (2-gram集合, 型番集合)"""
    s = name.translate(ZEN).lower()
    s = re.sub(r"[【\[［《〈].*?[】\]］》〉]", " ", s)  # 墨付き括弧内はほぼ宣伝
    codes = set(re.findall(r"[a-z]{1,4}-?\d{2,5}[a-z]?", s)) - {"45l"}
    s = re.sub(NOISE, " ", s)
    for w in COMMON:
        s = s.replace(w, " ")
    s = re.sub(r"[\d.]+\s*(?:個入り|個入|個|回分|回|錠|粒|枚入り|枚入|枚|本入り|本入|本組|本|袋|箱|冊|kg|g|ml|l|p|パック)?", " ", s)
    s = re.sub(r"[^\w]|_", "", s)
    return {s[i:i + 2] for i in range(len(s) - 1)}, codes


def similar(a, b, th=0.35):
    """型番が両方にあって食い違えば別商品。それ以外は2-gramのJaccard係数で判定"""
    (ga, ca), (gb, cb) = a, b
    if ca and cb:
        return bool(ca & cb)  # 型番が両方にあれば型番だけで判定（HX6014互換どうしは同じ扱い）
    if not ga or not gb:
        return False
    return len(ga & gb) / len(ga | gb) >= th


def product_line(name, cat):
    """カテゴリ設定の lines（ブランド→[(シリーズ名, 正規表現)]）で決まるシリーズ名。該当なしは None"""
    low = name.translate(ZEN).lower()
    for brand, aliases in cat.get("brands", {}).items():
        if any(a in low for a in aliases):
            for label, pat in cat.get("lines", {}).get(brand, []):
                if re.search(pat, low):
                    return f"{brand} {label}"
            return brand
    return None


def parse_volumes(name):
    """全巻セットの冊数と状態。'1-30巻 中古' -> (30, '1〜30巻・中古')、'全28巻' -> (28, '全28巻')。読めなければ (None, '')"""
    s = name.translate(ZEN)
    if re.search(r"選べる|選択|バラ売り|単品|1冊から|お好きな", s):
        return None, ""
    m = re.search(r"(\d{1,3})\s*[-~～〜ー－―]\s*(\d{1,3})\s*巻", s)
    if m and int(m.group(2)) > int(m.group(1)):
        a, b = int(m.group(1)), int(m.group(2))
        n, label = b - a + 1, f"{a}〜{b}巻"
    else:
        m = re.search(r"全\s*(\d{1,3})\s*巻", s) or re.search(r"(\d{1,3})\s*冊\s*(?:セット|入)?", s)
        if not m:
            return None, ""
        n, label = int(m.group(1)), (f"全{m.group(1)}巻" if "巻" in m.group(0) else f"{m.group(1)}冊")
    if not 3 <= n <= 200:
        return None, ""
    used = re.search(r"中古|レンタル落ち|レンタルアップ|USED|古本|コンディション|状態[:：(（]", s, re.I)
    state = "中古" if used else ("新品" if "新品" in s or "新刊" in s else "")
    return n, label + (f"・{state}" if state else "")


def add_scores(rows):
    """総合点: 単価の安さ(最安=1)と評価(件数が少ないほど★4.0に寄せるベイズ平均)を半分ずつ。
    ポイント込み実質単価も付ける（楽天の基本1倍は全商品共通なので、それを超える分だけ差し引く）"""
    if not rows:
        return rows
    c = 4.0  # レビューが少ない商品は★4.0に寄せる（少数の★5で上位に来ないように）
    m = 30   # この件数のレビューで、自分の評価と★4.0が半々になる
    best = min(r["unit_price"] for r in rows)
    for r in rows:
        bayes = (r["reviews"] * r["rating"] + m * c) / (r["reviews"] + m)
        r["score"] = round(50 * best / r["unit_price"] + 50 * bayes / 5, 1)
        r["eff_unit"] = r["unit_price"] * (1 - (max(r.get("point", 1), 1) - 1) / 100)
    return rows


def rank(items, cat):
    rows = []
    for it in items:
        if any(w in it["itemName"] for w in cat.get("ng", []) + NG_ALL):
            continue
        if cat.get("must") and not any(w in it["itemName"] for w in cat["must"]):
            continue
        if any(w not in it["itemName"] for w in cat.get("must_all", [])):
            continue
        if cat.get("size_re"):  # 紙おむつ: 狙いのサイズがあり、ほかのサイズが混ざっていない
            zn = it["itemName"].translate(ZEN)
            if not re.search(cat["size_re"], zn) or re.search(cat["size_ng_re"], zn):
                continue
        note = ""
        if cat.get("manga"):  # 全巻セット: 冊数と新品/中古
            n, note = parse_volumes(it["itemName"])
            if n and it.get("shopName") == "楽天ブックス" and "中古" not in note and "新品" not in note:
                note += "・新品"  # 楽天ブックスは新品のみ
            if n and n < cat.get("min_vol", 0):
                continue
        elif cat.get("parser"):  # 「ロール数×長さ」のように2つの数字を掛けるジャンル
            n = parse_product(it["itemName"], **cat["parser"])
        else:
            pname = re.sub(cat["strip"], " ", it["itemName"].translate(ZEN)) if cat.get("strip") else it["itemName"]
            if cat.get("boxes"):
                pname = box_sets(pname)
            n = parse_count(pname, cat["words"], *cat.get("range", (5, 3000)))
        if not n or it.get("reviewCount", 0) < cat["min_reviews"]:
            continue
        if cat.get("compat"):  # 替えブラシ: 純正と互換で値段の桁が違うので印を付ける
            note = "互換品" if re.search(r"互換|交換用|対応", it["itemName"]) else ("純正" if re.search(r"純正|正規品", it["itemName"]) else "")
        if cat.get("tags"):  # ペットフード: 年齢・体格の印
            note = "・".join(lb for pat, lb in cat["tags"] if re.search(pat, it["itemName"]))
        price = it["itemPrice"]
        if price < cat.get("min_price", 0):  # 全巻セットで数百円は1冊だけの出品などの読み違い
            continue
        rows.append({
            "name": it["itemName"], "shop": it.get("shopName", ""),
            "price": price, "count": n, "unit_price": price / (n / cat.get("per", 1)),
            "free_ship": it.get("postageFlag") == 0,
            "reviews": it.get("reviewCount", 0), "rating": it.get("reviewAverage", 0),
            "url": it.get("affiliateUrl") or it.get("itemUrl"),
            "img": (it.get("mediumImageUrls") or [""])[0],
            "rate": float(it.get("affiliateRate") or 0),
            "note": note,
            "point": int(it.get("pointRate") or 1),
            "code": it.get("itemCode") or it.get("itemUrl", ""),
        })
    rows.sort(key=lambda r: r["unit_price"])
    # 相場の35%未満（純正と互換が混ざるジャンルは15%未満）は数量の読み違いの可能性が高いので載せない
    if len(rows) >= 5:
        med = rows[len(rows) // 2]["unit_price"]
        rows = [r for r in rows if r["unit_price"] >= med * cat.get("outlier", 0.35)]
    if not cat.get("group", True):  # 全巻セットのようにショップ・状態違いを比べたいジャンル
        seen, uniq = set(), []
        for r in rows:  # 同じショップが同じ値段・冊数で二重に出品しているものは1行に
            key = (r["shop"], r["price"], r["count"])
            if key not in seen:
                seen.add(key)
                r["others"] = 0
                uniq.append(r)
        return add_scores(uniq[:30])
    # 同じ商品（ショップ違い・袋数違い）は1行にまとめ、1回あたり最安の出品だけを載せる
    groups = []
    for r in rows:  # rows は単価の安い順なので、各グループの先頭が最安
        sig = product_line(r["name"], cat) or signature(r["name"])
        for g in groups:
            if sig == g["sig"] or (not isinstance(sig, str) and not isinstance(g["sig"], str) and similar(sig, g["sig"])):
                g["others"] += 1
                break
        else:
            groups.append({"sig": sig, "row": r, "others": 0})
    out = []
    for g in groups[:30]:
        g["row"]["others"] = g["others"]
        out.append(g["row"])
    return add_scores(out)


def short(c):
    """ナビ用の短い名前: 「ゴミ袋 45L 1枚あたり単価ランキング」→「ゴミ袋 45L」"""
    per = c.get("per_text", f"1{c['unit']}あたり")
    return c["title"].replace("単価ランキング", "").replace(per, "").strip()


def clean_name(name, n=60):
    """表示用の商品名: 【送料無料】＼ポイント5倍／★最安★ などの宣伝を取り除く"""
    s = re.sub(r"【[^】]*】|［[^］]*］|\[[^\]]*\]|＼[^／]*／|★[^★]*★|☆[^☆]*☆|《[^》]*》|◆|◇|■|□", " ", name)
    s = re.sub(r"\s+", " ", s).strip(" 　|｜/")
    return (s[:n] + "…") if len(s) > n else (s or name[:n])


def typical_avg(rows):
    """平均単価。相場（中央値）の3倍を超える割高品は平均を押し上げて「○%安い」を誇張するので除く"""
    us = sorted(r["unit_price"] for r in rows)
    med = us[len(us) // 2]
    keep = [u for u in us if u <= med * 3] or us
    return sum(keep) / len(keep)


def median_unit(rows):
    """単価の中央値（相場）。割高な純正品や中古・新品の混在に引っぱられない"""
    us = sorted(r["unit_price"] for r in rows)
    return us[len(us) // 2]


def best_row(rows):
    """送料を含めて比べやすい「最安」: 送料無料の中の最安。送料無料がなければ表示価格の最安"""
    return next((r for r in rows if r["free_ship"]), rows[0]) if rows else None


def pick_rows(rows, cat=None):
    """冒頭の「結論」に出す3つ。送料別の商品は送料を含まない単価なので、1枠目は送料無料の最安にする"""
    if not rows:
        return []
    good = lambda r: r["rating"] >= 4.3 and r["reviews"] >= 100
    top_score = max(rows, key=lambda r: r.get("score", 0))
    first = best_row(rows)
    label = ("送料込みでいちばん安い" if first["free_ship"] else "いちばん安い（送料別）") +             ("・総合1位" if first is top_score else ("・高評価" if good(first) else ""))
    picks, used = [(label, first)], {id(first)}
    tests = [("総合おすすめ（安さ×評価）", lambda r: r is top_score)]
    if cat and cat.get("compat"):  # 替えブラシは純正を探す人も多い
        tests.insert(0, ("純正でいちばん安い", lambda r: r.get("note") == "純正"))
    if cat and cat.get("manga"):
        new = lambda r: "新品" in r.get("note", "")
        old = lambda r: "中古" in r.get("note", "")
        picks, used = [], set()
        for label, test in [("新品でいちばん安い", new), ("中古でいちばん安い", old)]:
            r = next((r for r in rows if test(r) and r["free_ship"]), None) or next((r for r in rows if test(r)), None)
            if r:
                used.add(id(r))
                picks.append((label + ("" if r["free_ship"] else "（送料別）"), r))
        r = next((r for r in rows if id(r) not in used), None)
        if r and r["unit_price"] < min(p[1]["unit_price"] for p in picks or [(0, {"unit_price": 1e9})]):
            picks.append(("新品・中古の表記なしで最安" + ("" if r["free_ship"] else "（送料別）"), r))
        if picks:
            return picks
    # 送料別でも表示価格がもっと安いものがあれば、送料別と明記して並べる
    tests.append(("表示価格の最安（送料別）", lambda r: not r["free_ship"] and r["unit_price"] < first["unit_price"]))
    for label, test in tests:
        r = next((r for r in rows if test(r) and id(r) not in used), None)
        if r:
            used.add(id(r))
            picks.append((label if r["free_ship"] or "送料別" in label else label + "（送料別）", r))
    return picks


def trend_html(hist, unit):
    """直近30日の最安単価の推移（小さな折れ線）と買い時バッジ"""
    pts = hist[-30:]
    if not pts:
        return ""
    vals = [p[1] for p in pts]
    now = vals[-1]
    if len(pts) < 7:
        badge = f"<span class=tb>価格を記録中（{len(pts)}日目）</span>"
    elif now <= min(vals):
        badge = f"<span class='tb hot'>過去{len(vals)}日で最安値</span>"
    elif now <= sorted(vals)[len(vals) // 4]:
        badge = f"<span class='tb ok'>過去{len(vals)}日の中でも安い水準</span>"
    else:
        badge = f"<span class=tb>過去{len(vals)}日の最安は {min(vals):.1f}円/{html.escape(unit)}</span>"
    svg = ""
    if len(pts) >= 2:
        W, H, P = 240, 48, 4
        lo, hi = min(vals), max(vals)
        span = (hi - lo) or 1
        xy = [(P + i * (W - 2 * P) / (len(vals) - 1), H - P - (v - lo) / span * (H - 2 * P)) for i, v in enumerate(vals)]
        line = " ".join(f"{x:.1f},{y:.1f}" for x, y in xy)
        area = f"{xy[0][0]:.1f},{H - P} {line} {xy[-1][0]:.1f},{H - P}"
