def brand_of(name, brands):
    """商品名でいちばん前に出てくるブランド（後ろのほうの「◯◯の代わりに」などの検索用の言葉に引っぱられにくい）"""
    low = name.lower()
    hits = [(low.find(a), b) for b, al in brands.items() for a in al if a in low]
    return min(hits)[1] if hits else None
